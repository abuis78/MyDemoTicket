#!/usr/bin/env bash
# Install / uninstall MyDemoTicket as a systemd service behind Caddy (TLS).
#
#   sudo deploy/install.sh                       # install or update (idempotent)
#   deploy/install.sh --dry-run                  # render everything into a temp dir, change nothing
#   deploy/install.sh --dry-run --root /tmp/x    # same, into a chosen directory
#   sudo deploy/install.sh --uninstall           # remove service, code, Caddy site (keeps data)
#   sudo deploy/install.sh --uninstall --purge-data
#
# Options (defaults in brackets):
#   --domain NAME      public host name                [ticket.soc-games.com]
#   --port N           local port of the app            [8080]
#   --user NAME        system user                      [mydemoticket]
#   --install-dir DIR  code location                    [/opt/mydemoticket]
#   --data-dir DIR     SQLite + credentials             [/var/lib/mydemoticket]
#   --python PATH      Python 3.9+ interpreter          [first python3 on PATH]
#   --root DIR         prefix for all written files (testing); implied temp dir with --dry-run
#
# No secrets are handled here. Initial credentials are generated by the app on first
# start into <data-dir>/initial-credentials.txt (mode 0600).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
SRC_PKG="$REPO_DIR/ticket-system/mydemoticket"

DOMAIN="ticket.soc-games.com"
PORT="8080"
SVC_USER="mydemoticket"
INSTALL_DIR="/opt/mydemoticket"
DATA_DIR="/var/lib/mydemoticket"
PYTHON_BIN=""
ROOT=""
DRY_RUN=0
UNINSTALL=0
PURGE_DATA=0

UNIT_PATH="/etc/systemd/system/mydemoticket.service"
ENV_FILE="/etc/mydemoticket/env"
CADDY_MAIN="/etc/caddy/Caddyfile"
CADDY_SITE="/etc/caddy/mydemoticket.caddy"
MARKER="# managed by mydemoticket"

usage() { sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --user) SVC_USER="$2"; shift 2 ;;
    --install-dir) INSTALL_DIR="$2"; shift 2 ;;
    --data-dir) DATA_DIR="$2"; shift 2 ;;
    --python) PYTHON_BIN="$2"; shift 2 ;;
    --root) ROOT="$2"; shift 2 ;;
    --dry-run) DRY_RUN=1; shift ;;
    --uninstall) UNINSTALL=1; shift ;;
    --purge-data) PURGE_DATA=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

case "$PORT" in ''|*[!0-9]*) echo "--port must be a number" >&2; exit 2 ;; esac
case "$DOMAIN" in ''|*[!A-Za-z0-9.-]*) echo "--domain contains invalid characters" >&2; exit 2 ;; esac
case "$SVC_USER" in ''|*[!a-z0-9_-]*) echo "--user contains invalid characters" >&2; exit 2 ;; esac

if [ "$DRY_RUN" -eq 1 ] && [ -z "$ROOT" ]; then
  ROOT="$(mktemp -d "${TMPDIR:-/tmp}/mydemoticket-dryrun.XXXXXX")"
fi
if [ "$DRY_RUN" -eq 0 ] && [ -z "$ROOT" ] && [ "$(id -u)" -ne 0 ]; then
  echo "Please run as root (sudo), or use --dry-run." >&2
  exit 1
fi
if [ -z "$PYTHON_BIN" ]; then
  PYTHON_BIN="$(command -v python3 || true)"
  [ -n "$PYTHON_BIN" ] || PYTHON_BIN="/usr/bin/python3"
fi

say() { echo "==> $*"; }
# System-changing commands: executed for real, only printed with --dry-run or --root.
run() {
  if [ "$DRY_RUN" -eq 1 ] || [ -n "$ROOT" ]; then
    echo "    [skip] $*"
  else
    "$@"
  fi
}
p() { echo "${ROOT}$1"; }   # path inside the (optional) root prefix

render() {  # render TEMPLATE DEST MODE
  local tmp
  tmp="$(mktemp)"
  sed -e "s|@USER@|$SVC_USER|g" -e "s|@PYTHON@|$PYTHON_BIN|g" -e "s|@INSTALL_DIR@|$INSTALL_DIR|g" \
      -e "s|@DATA_DIR@|$DATA_DIR|g" -e "s|@PORT@|$PORT|g" -e "s|@DOMAIN@|$DOMAIN|g" \
      -e "s|@ENV_FILE@|$ENV_FILE|g" "$1" > "$tmp"
  mkdir -p "$(dirname "$(p "$2")")"
  install -m "$3" "$tmp" "$(p "$2")"
  rm -f "$tmp"
  say "wrote $(p "$2")"
}

is_managed() { [ -f "$1" ] && grep -qF "$MARKER" "$1"; }

do_install() {
  say "Installing MyDemoTicket (domain $DOMAIN, port $PORT, user $SVC_USER)"
  [ -d "$SRC_PKG" ] || { echo "Package not found: $SRC_PKG" >&2; exit 1; }
  if [ -z "$ROOT" ] && ! "$PYTHON_BIN" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)'; then
    echo "$PYTHON_BIN is older than Python 3.9" >&2; exit 1
  fi

  if ! id "$SVC_USER" >/dev/null 2>&1; then
    say "create system user $SVC_USER"
    run useradd --system --home-dir "$DATA_DIR" --shell /usr/sbin/nologin "$SVC_USER"
  fi

  say "copy code to $(p "$INSTALL_DIR")"
  mkdir -p "$(p "$INSTALL_DIR")"
  rm -rf "$(p "$INSTALL_DIR")/mydemoticket"
  cp -R "$SRC_PKG" "$(p "$INSTALL_DIR")/mydemoticket"
  find "$(p "$INSTALL_DIR")" -name '__pycache__' -type d -prune -exec rm -rf {} +
  chmod -R u=rwX,go=rX "$(p "$INSTALL_DIR")"

  say "data directory $(p "$DATA_DIR")"
  mkdir -p "$(p "$DATA_DIR")"
  chmod 700 "$(p "$DATA_DIR")"
  run chown "$SVC_USER:$SVC_USER" "$DATA_DIR"

  if [ ! -f "$(p "$ENV_FILE")" ]; then
    mkdir -p "$(dirname "$(p "$ENV_FILE")")"
    ( umask 077
      { echo "$MARKER"
        echo "# Optional, read once on first start. Leave unset to get random values in"
        echo "# $DATA_DIR/initial-credentials.txt."
        echo "#MYDEMOTICKET_ADMIN_PASSWORD="
        echo "#MYDEMOTICKET_ADMIN_TOKEN="
      } > "$(p "$ENV_FILE")" )
    say "wrote $(p "$ENV_FILE") (0600, no secrets)"
  fi

  render "$SCRIPT_DIR/mydemoticket.service.template" "$UNIT_PATH" 644

  if [ -f "$(p "$CADDY_MAIN")" ] && ! is_managed "$(p "$CADDY_MAIN")"; then
    render "$SCRIPT_DIR/Caddyfile.template" "$CADDY_SITE" 644
    if ! grep -qF "import $CADDY_SITE" "$(p "$CADDY_MAIN")"; then
      say "existing $CADDY_MAIN kept; add this line to it:  import $CADDY_SITE"
    fi
  else
    render "$SCRIPT_DIR/Caddyfile.template" "$CADDY_MAIN" 644
  fi

  if ! command -v caddy >/dev/null 2>&1; then
    say "caddy not found on PATH - install it first (see deploy/README.md)"
  fi
  run systemctl daemon-reload
  run systemctl enable mydemoticket.service
  run systemctl restart mydemoticket.service
  run systemctl reload-or-restart caddy
  say "done. Check: curl -s https://$DOMAIN/api/v1/health"
  say "initial credentials (first start only): $DATA_DIR/initial-credentials.txt (root/$SVC_USER only)"
}

do_uninstall() {
  say "Uninstalling MyDemoTicket"
  run systemctl disable --now mydemoticket.service
  rm -f "$(p "$UNIT_PATH")" && say "removed $(p "$UNIT_PATH")"
  run systemctl daemon-reload
  rm -rf "$(p "$INSTALL_DIR")/mydemoticket" && say "removed $(p "$INSTALL_DIR")/mydemoticket"
  rmdir "$(p "$INSTALL_DIR")" 2>/dev/null || true
  if is_managed "$(p "$ENV_FILE")"; then
    rm -f "$(p "$ENV_FILE")" && say "removed $(p "$ENV_FILE")"
  elif [ -f "$(p "$ENV_FILE")" ]; then
    say "kept $(p "$ENV_FILE") (edited by you; delete manually if no longer needed)"
  fi
  rmdir "$(dirname "$(p "$ENV_FILE")")" 2>/dev/null || true
  for f in "$CADDY_SITE" "$CADDY_MAIN"; do
    if is_managed "$(p "$f")"; then rm -f "$(p "$f")" && say "removed $(p "$f")"; fi
  done
  say "if your Caddyfile imports $CADDY_SITE, remove that line"
  run systemctl reload-or-restart caddy
  if [ "$PURGE_DATA" -eq 1 ]; then
    rm -rf "$(p "$DATA_DIR")" && say "removed data $(p "$DATA_DIR")"
    if id "$SVC_USER" >/dev/null 2>&1; then run userdel "$SVC_USER"; fi
  else
    say "kept data in $(p "$DATA_DIR") (use --purge-data to delete it)"
  fi
}

[ -n "$ROOT" ] && say "writing below root prefix: $ROOT$([ "$DRY_RUN" -eq 1 ] && echo ' (dry run)')"
if [ "$UNINSTALL" -eq 1 ]; then do_uninstall; else do_install; fi
